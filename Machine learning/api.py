@router.post("/pipeline/process", response_model=PipelineProcessResponse, summary="Execute Full Verification Pipeline")
def run_full_pipeline(request: PipelineProcessRequest):
    """
    Convenience endpoint orchestrating the full ML sequence in one call:
    1. Analysis -> Insights
    2. Forecaster -> 90-day HbA1c forecast
    3. Triage Agent -> Priority & Reason
    4. Summarizer -> English & Hindi draft summaries
    """
    try:
        raw_all = [m.model_dump() for m in request.all_measurements]
        
        # 1. Analyze
        insights_data = analyze_patient(raw_all)
        
        # 2. Triage
        triage_data = triage(patient_id=request.patient_id, insights=insights_data)
        
        # 3. Forecast
        forecast_data = forecast_hba1c(raw_all)
        
        # 4. Latest measurements for summaries
        if request.latest_measurements:
            raw_latest = [m.model_dump() for m in request.latest_measurements]
        else:
            sorted_m = sorted(raw_all, key=lambda x: x.get("date", ""), reverse=True)
            if sorted_m:
                latest_date = sorted_m[0].get("date")
                raw_latest = [m for m in sorted_m if m.get("date") == latest_date]
            else:
                raw_latest = []
                
        # 5. Summaries in EN & HI
        summary_en = draft_summary(raw_latest, insights_data, lang="en")
        summary_hi = draft_summary(raw_latest, insights_data, lang="hi")
        
        return PipelineProcessResponse(
            patient_id=request.patient_id,
            insights=[Insight(**i) for i in insights_data],
            forecast=Forecast(**forecast_data),
            triage=TriageResult(**triage_data),
            summary_en=summary_en,
            summary_hi=summary_hi
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Full pipeline execution failed: {str(e)}"
        )


