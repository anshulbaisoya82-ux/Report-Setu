@router.post("/extract/file", response_model=ExtractedReport, summary="Extract Report From Document")
async def extract_from_file(file: UploadFile = File(...)):
    """
    Accepts a lab report file (PDF, PNG, JPG, or TXT), executes OCR / document parsing,
    and returns standardized measurements with reference flags and sanity checks.
    """
    suffix = os.path.splitext(file.filename or "")[1] or ".tmp"
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=suffix)
    try:
        shutil.copyfileobj(file.file, temp_file)
        temp_file.close()

        extracted_data = extract_report(temp_file.name)
        return ExtractedReport(**extracted_data)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Report extraction failed: {str(e)}"
        )
    finally:
        if os.path.exists(temp_file.name):
            try:
                os.remove(temp_file.name)
            except Exception:
                pass


@router.post("/extract/text", response_model=ExtractedReport, summary="Extract Report From Raw Text")
def extract_from_text(request: ExtractTextRequest):
    """
    Extracts laboratory measurements from raw unformatted report text string.
    """
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".txt", mode="w", encoding="utf-8")
    try:
        temp_file.write(request.raw_text)
        temp_file.close()

        extracted_data = extract_report(temp_file.name)
        return ExtractedReport(**extracted_data)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Text report extraction failed: {str(e)}"
        )
    finally:
        if os.path.exists(temp_file.name):
            try:
                os.remove(temp_file.name)
            except Exception:
                pass


