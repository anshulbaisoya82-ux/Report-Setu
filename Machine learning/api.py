@router.post("/analysis/analyze", response_model=List[Insight], summary="Analyze Longitudinal Patient Trends")
def run_analysis(request: AnalyzePatientRequest):
    """
    Compares latest measurements against patient history:
    - Reference range violations (high, low, critical)
    - Trend slopes and directions (rising / falling / stable)
    - Unusual jumps / acute changes (Isolation Forest / z-score)
    Returns structured Insight items with cited evidence and dates.
    """
    try:
        raw_m = [m.model_dump() for m in request.measurements]
        insights_data = analyze_patient(raw_m)
        return [Insight(**i) for i in insights_data]
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Analysis engine error: {str(e)}"
        )


@router.post("/forecast/hba1c", response_model=Forecast, summary="Forecast 90-Day HbA1c Trajectory")
def run_forecast(request: ForecastHbA1cRequest):
    """
    Calculates 90-day linear regression forecast for HbA1c with confidence intervals.
    Returns estimate: null and warning when fewer than 3 readings exist.
    """
    try:
        raw_m = [m.model_dump() for m in request.measurements]
        res = forecast_hba1c(raw_m)
        return Forecast(**res)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Forecasting error: {str(e)}"
        )


@router.post("/triage", response_model=TriageResult, summary="LangGraph Clinical Triage Agent")
def run_triage(request: TriagePatientRequest):
    """
    LangGraph Agent that evaluates patient insights and assigns a clinical priority
    ('critical', 'review', or 'stable') along with an explainable 1-line reason.
    """
    try:
        raw_insights = [i.model_dump() for i in request.insights]
        result = triage(patient_id=request.patient_id, insights=raw_insights)
        return TriageResult(**result)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Triage agent error: {str(e)}"
        )


