@router.post("/summary/draft", response_model=DraftSummaryResponse, summary="Draft Plain-Language Patient Summary")
def run_draft_summary(request: DraftSummaryRequest):
    """
    Drafts an empathetic, non-alarmist patient summary in English or Hindi.
    Strict constraints:
    - Never names a disease (no 'diabetes', 'anemia', 'cancer', etc.)
    - Never names a medicine (no 'metformin', 'insulin', etc.)
    - At most 120 words.
    """
    try:
        raw_m = [m.model_dump() for m in request.measurements]
        raw_i = [i.model_dump() for i in request.insights]
        summary_text = draft_summary(raw_m, raw_i, lang=request.lang)
        words = summary_text.split()
        return DraftSummaryResponse(
            summary=summary_text,
            lang=request.lang,
            word_count=len(words)
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Summary drafting error: {str(e)}"
        )


@router.post("/chat", response_model=ChatResponse, summary="Patient Chat Assistant with Guardrails")
def run_patient_chat(request: PatientChatRequest):
    """
    Answers patient inquiries grounded strictly in the doctor-approved summary and MedlinePlus.
    Guardrail: Sets `escalate: true` for medical advice, medications, diagnoses, or emergencies.
    """
    try:
        res = patient_chat(
            question=request.question,
            approved_summary=request.approved_summary,
            history=request.history
        )
        return ChatResponse(
            answer=res["answer"],
            escalate=res["escalate"]
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Patient chat error: {str(e)}"
        )


